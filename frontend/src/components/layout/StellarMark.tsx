import type { ReactNode } from 'react'

const STELLAR_URL = 'https://stellar.org'

type StellarTone = 'dark' | 'light'
type StellarVariant = 'mark' | 'wordmark'

export function StellarMark({
  size = 18,
  tone = 'dark',
  variant = 'mark',
  linked = true,
  caption,
  children,
  className = '',
}: {
  size?: number
  tone?: StellarTone
  variant?: StellarVariant
  linked?: boolean
  caption?: string
  children?: ReactNode
  className?: string
}) {
  const palette = tone === 'dark' ? 'text-white/90 hover:text-white' : 'text-ink/80 hover:text-ink'
  const classes = [
    'stellar-mark inline-flex shrink-0 items-center gap-1.5',
    'motion-safe:transition-opacity motion-reduce:transition-none',
    'opacity-90 hover:opacity-100',
    'focus-visible:outline focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-yellow',
    palette,
    className,
  ].join(' ')
  const label = caption ? (
    <span className="text-[10px] font-semibold uppercase tracking-[0.16em]">{caption}</span>
  ) : (
    children
  )
  const glyph = variant === 'wordmark' ? <Wordmark height={size} /> : <Mark height={size} />

  if (!linked) {
    return (
      <span className={classes}>
        {glyph}
        {label}
      </span>
    )
  }

  return (
    <a href={STELLAR_URL} target="_blank" rel="noreferrer" aria-label="Stellar" className={classes}>
      {glyph}
      {label}
    </a>
  )
}

